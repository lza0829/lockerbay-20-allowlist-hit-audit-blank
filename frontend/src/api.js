async function req(path, opts = {}) {
  const res = await fetch(path, {
    headers: { 'Content-Type': 'application/json', ...(opts.headers || {}) },
    ...opts,
  })
  if (!res.ok) throw new Error(await res.text())
  return res.json()
}

export const api = {
  health: () => req('/api/health'),
  overview: () => req('/api/overview'),
  bay: () => req('/api/bay'),
  occupancies: () => req('/api/occupancies'),
  events: () => req('/api/events'),
  quarantine: () => req('/api/quarantine'),
  proofs: () => req('/api/occupancy-proofs'),
  settings: () => req('/api/settings'),
  eventTypes: () => req('/api/settings/event-types'),
  setEventTypes: (allowed) =>
    req('/api/settings/event-types', { method: 'PUT', body: JSON.stringify({ allowed }) }),
  eventTypeVerify: () => req('/api/event-type-verify'),
  setOverdue: (overdue_hours) =>
    req('/api/settings/overdue-hours', { method: 'PUT', body: JSON.stringify({ overdue_hours }) }),
  ingest: () => req('/api/ingest/run', { method: 'POST', body: '{}' }),
  allowlistHitAudits: () => req('/api/allowlist-hit-audits'),
}
